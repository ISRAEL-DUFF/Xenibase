#!/bin/sh
# Install or upgrade Xenibase on this host with Docker Compose (spec §11.1).
#
#   cd deploy/compose && ./install.sh
#
# On first run it asks for the web UI hostname and an email for Let's
# Encrypt (or reads XENIBASE_UI_DOMAIN and XENIBASE_ACME_EMAIL from the
# environment), writes .env with fresh secrets, builds the images, starts
# the stack, and prints the one-time setup code. Run it again after
# `git checkout <new tag>` to upgrade: .env is kept.
#
# XENIBASE_BUILD_FLAGS is passed to `docker build` (e.g. a proxy CA secret);
# COMPOSE_FILE and COMPOSE_PROJECT_NAME work as for docker compose.
set -eu
cd "$(dirname "$0")"

command -v docker >/dev/null || { echo "Docker is required: https://docs.docker.com/engine/install/" >&2; exit 1; }
docker compose version >/dev/null 2>&1 || { echo "Docker Compose v2 is required." >&2; exit 1; }

rand() { head -c "$1" /dev/urandom | base64 | tr -d '\n'; }
rand_url() { rand "$1" | tr '+/' '-_' | tr -d '='; }

if [ ! -f .env ]; then
	ui_domain=${XENIBASE_UI_DOMAIN:-}
	email=${XENIBASE_ACME_EMAIL:-}
	if [ -z "$ui_domain" ]; then
		printf 'Web UI hostname (e.g. xenibase.example.com): '
		read -r ui_domain
	fi
	if [ -z "$email" ]; then
		printf 'Email for Let'"'"'s Encrypt notices: '
		read -r email
	fi
	case "$ui_domain" in
	"" | *[!A-Za-z0-9.-]*) echo "invalid hostname: '$ui_domain'" >&2; exit 1 ;;
	esac
	case "$email" in
	*@*.*) ;;
	*) echo "invalid email: '$email'" >&2; exit 1 ;;
	esac
	public_ip=${XENIBASE_PUBLIC_IPS:-$(curl -fsS --max-time 5 https://api.ipify.org 2>/dev/null || true)}
	umask 077
	cat > .env <<ENV
# Generated by install.sh. Back this file up: XENIBASE_MASTER_KEY decrypts
# every secret Xenibase stores, and losing it loses them.
XENIBASE_UI_DOMAIN=${ui_domain}
XENIBASE_ACME_EMAIL=${email}
XENIBASE_PUBLIC_IPS=${public_ip}
XENIBASE_MASTER_KEY=$(rand 32)
METADATA_DB_PASSWORD=$(rand_url 24)
SHARED_ADMIN_PASSWORD=$(rand_url 24)
POOLER_ADMIN_PASSWORD=$(rand_url 24)
ENV
	echo "Wrote .env (mode 600)."
fi
# Added in later releases; older .env files lack them.
grep -q '^AGENT_BOOTSTRAP_TOKEN=' .env || echo "AGENT_BOOTSTRAP_TOKEN=$(rand_url 32)" >> .env
grep -q '^XENIBASE_PUBLIC_URL=' .env || echo "XENIBASE_PUBLIC_URL=https://$(grep '^XENIBASE_UI_DOMAIN=' .env | cut -d= -f2-)" >> .env

# Dedicated instances and agent-run shared clusters run this image
# (PostgreSQL + WAL-G, one image per supported major).
# shellcheck disable=SC2086 # XENIBASE_BUILD_FLAGS is a list of flags
for major in 17 18; do
	docker build ${XENIBASE_BUILD_FLAGS:-} --build-arg PG_MAJOR=$major -t xenibase-postgres:$major-walg3.0.9 ../images/postgres
done
# The binaries report the release they were built from (git describe: the tag
# itself on a tagged checkout), which upgrade.sh and the Nodes page rely on.
version=$(git describe --tags --always 2>/dev/null || echo dev)
commit=$(git rev-parse --short HEAD 2>/dev/null || echo unknown)
# shellcheck disable=SC2086
docker build ${XENIBASE_BUILD_FLAGS:-} --build-arg "VERSION=$version" --build-arg "COMMIT=$commit" -t "${XENIBASE_IMAGE:-xenibase:local}" ../..
# shellcheck disable=SC2086
docker build ${XENIBASE_BUILD_FLAGS:-} --build-arg "VERSION=$version" --build-arg "COMMIT=$commit" --target agent -t "${XENIBASE_AGENT_IMAGE:-xenibase-agent:local}" ../..
# The edge is built here too, once backend services are on: its image is local,
# so without this an upgrade keeps running the old edge.
if grep -qE '^COMPOSE_PROFILES=.*services' .env && [ -z "${XENIBASE_EDGE_IMAGE:-}" ]; then
	# shellcheck disable=SC2086
	docker build ${XENIBASE_BUILD_FLAGS:-} --build-arg "VERSION=$version" --build-arg "COMMIT=$commit" -f ../edge/Dockerfile -t xenibase-edge:local ../..
fi
docker compose up -d --no-build --wait
# The poolers bind-mount single config files. A checkout replaces the file
# (a new inode), so a running pooler keeps reading the old one, or a
# truncated copy of it, and compose sees no change. Recreate them so they
# pick up this version's config; clients reconnect within a second or two.
docker compose up -d --no-build --wait --force-recreate --no-deps pooler-session pooler-tx

echo
echo "Xenibase is running: https://$(grep '^XENIBASE_UI_DOMAIN=' .env | cut -d= -f2-)"
# The server logs JSON ("setup_code":"…") or text (setup_code=…).
code=$(docker compose logs xenibase-server 2>/dev/null | grep -oE 'setup_code"?[=:]"?[A-Za-z0-9_=-]+' | tail -1 | sed -E 's/^setup_code"?[=:]"?//')
if [ -n "$code" ]; then
	echo "First-run setup code: $code"
else
	echo "(Setup is already done, or see: docker compose logs xenibase-server | grep setup_code)"
fi
