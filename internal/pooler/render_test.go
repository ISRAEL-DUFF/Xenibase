const verifier = "SCRAM-SHA-256$4096:c2FsdA==$c3RvcmVk:c2VydmVy"

func TestRender(t *testing.T) {
	db, ul, _, err := Render(Config{
		Routes: []Route{
			{Database: "todo_8xq1", Host: "10.0.0.5", Port: 5432, PoolSize: 5, MaxDBConnections: 20},
			{Database: "blog_k2f9", Host: "shared-pg", Port: 5432},
		},
		Users: []User{
			{Name: "todo_8xq1_owner", Secret: verifier},
			{Name: "blog_k2f9_owner", Secret: verifier},
		},
	})
	if err != nil {
		t.Fatal(err)
	}
	want := "; Generated by xenibase-server. Do not edit: changes are overwritten.\n[databases]\n" +
		"blog_k2f9 = host=shared-pg port=5432 dbname=blog_k2f9\n" +
		"todo_8xq1 = host=10.0.0.5 port=5432 dbname=todo_8xq1 pool_size=5 max_db_connections=20\n"
	if string(db) != want {
		t.Fatalf("databases.ini:\n%s\nwant:\n%s", db, want)
	}
	wantUL := `"blog_k2f9_owner" "` + verifier + "\"\n" + `"todo_8xq1_owner" "` + verifier + "\"\n"
	if string(ul) != wantUL {
		t.Fatalf("userlist:\n%s\nwant:\n%s", ul, wantUL)
	}
}

func TestRenderHBA(t *testing.T) {
	_, _, hba, err := Render(Config{Restrictions: []Restriction{{
		Databases: []string{"shop_k2f9", "shop_k2f9_ro"},
		Platform:  []string{"shop_k2f9_edge", "shop_k2f9_sla"},
		CIDRs:     []string{"102.89.10.4/32", "10.0.0.0/16"},
	}}})
	if err != nil {
		t.Fatal(err)
	}
	want := "# Generated by xenibase-server. Do not edit: changes are overwritten.\n" +
		"host shop_k2f9,shop_k2f9_ro shop_k2f9_edge,shop_k2f9_sla 0.0.0.0/0 scram-sha-256\n" +
		"host shop_k2f9,shop_k2f9_ro shop_k2f9_edge,shop_k2f9_sla ::/0 scram-sha-256\n" +
		"host shop_k2f9,shop_k2f9_ro all 102.89.10.4/32 scram-sha-256\n" +
		"host shop_k2f9,shop_k2f9_ro all 10.0.0.0/16 scram-sha-256\n" +
		"host shop_k2f9,shop_k2f9_ro all 0.0.0.0/0 reject\n" +
		"host shop_k2f9,shop_k2f9_ro all ::/0 reject\n" +
		"host all all 0.0.0.0/0 scram-sha-256\n" +
		"host all all ::/0 scram-sha-256\n"
	if string(hba) != want {
		t.Fatalf("hba.conf:\n%s\nwant:\n%s", hba, want)
	}
	// No allowlists: everyone, from anywhere, with SCRAM.
	if _, _, hba, _ := Render(Config{}); !strings.HasSuffix(string(hba), "host all all 0.0.0.0/0 scram-sha-256\nhost all all ::/0 scram-sha-256\n") {
		t.Fatalf("default hba.conf:\n%s", hba)
	}
	for _, bad := range []string{"10.0.0.1/16", "not a cidr", "10.0.0.0/16 trust"} {
		if _, _, _, err := Render(Config{Restrictions: []Restriction{{Databases: []string{"a_b"}, CIDRs: []string{bad}}}}); err == nil {
			t.Fatalf("CIDR %q was accepted", bad)
		}
	}
	if _, _, _, err := Render(Config{Restrictions: []Restriction{{Databases: []string{"a b"}, CIDRs: []string{"10.0.0.0/8"}}}}); err == nil {
		t.Fatal("a database name with a space was accepted")
	}
}

func TestRenderReadOnlyRoute(t *testing.T) {
	db, _, _, err := Render(Config{Routes: []Route{
		{Database: "p_abc_ro", BackendDB: "p_abc", Host: "10.0.0.6", MoreHosts: []string{"10.0.0.7"}, Port: 24411, PoolSize: 5, ReadOnly: true},
	}})
	if err != nil {
		t.Fatal(err)
	}
	want := "p_abc_ro = host=10.0.0.6,10.0.0.7 port=24411 dbname=p_abc connect_query='SET default_transaction_read_only = on' pool_size=5\n"
	if !strings.HasSuffix(string(db), want) {
		t.Fatalf("databases.ini:\n%s\nwant a line:\n%s", db, want)
	}
	if _, _, _, err := Render(Config{Routes: []Route{{Database: "x", Host: "h", MoreHosts: []string{"a port=1"}, Port: 1}}}); err == nil {
		t.Fatal("a host list entry with configuration in it was accepted")
	}
}

func TestReplicaHosts(t *testing.T) {
	same := func(r string) string { return r }
	reps := []store.PoolerReplicaRoutesRow{
		{Host: "a", Port: 7000, Region: "eu", InRotation: true},
		{Host: "b", Port: 7000, Region: "us", InRotation: true},
		{Host: "c", Port: 7001, Region: "us", InRotation: true},
		{Host: "d", Port: 7000, Region: "us", InRotation: false},
	}
	if h, p := replicaHosts(reps, "us", same); p != 7000 || strings.Join(h, ",") != "b" {
		t.Fatalf("us: %v %d", h, p)
	}
	if h, p := replicaHosts(reps, "eu", same); p != 7000 || strings.Join(h, ",") != "a" {
		t.Fatalf("eu: %v %d", h, p)
	}
	// No replica of its own: every one in rotation, on the shared port.
	if h, p := replicaHosts(reps, "af", same); p != 7000 || strings.Join(h, ",") != "a,b" {
		t.Fatalf("af: %v %d", h, p)
	}
	if h, _ := replicaHosts(reps[3:], "us", same); len(h) != 0 {
		t.Fatalf("none in rotation: %v", h)
	}
}

func TestRenderRejectsInjection(t *testing.T) {
	bad := []Config{
		{Routes: []Route{{Database: "x\n[pgbouncer]", Host: "h", Port: 1}}},
		{Routes: []Route{{Database: "x", Host: "h auth_user=postgres", Port: 1}}},
		{Routes: []Route{{Database: "x", Host: "h", Port: 0}}},
		{Routes: []Route{{Database: "x", Host: "h", Port: 1}, {Database: "x", Host: "h", Port: 1}}},
		{Users: []User{{Name: "u\"", Secret: verifier}}},
		{Users: []User{{Name: "u", Secret: "plaintext"}}},
		{Users: []User{{Name: "u", Secret: verifier + "\"\n\"admin\" \"x"}}},
	}
	for i, c := range bad {
		if _, _, _, err := Render(c); err == nil {
			t.Errorf("case %d accepted", i)
		}
	}
}

func TestWriteFileAtomic(t *testing.T) {
	dir := t.TempDir()
	p := filepath.Join(dir, "f")
	changed, err := WriteFileAtomic(p, []byte("a"), 0o640)
	if err != nil || !changed {
		t.Fatalf("first write: %v %v", changed, err)
	}
	if changed, _ := WriteFileAtomic(p, []byte("a"), 0o640); changed {
		t.Fatal("identical write reported a change")
	}
	if changed, _ := WriteFileAtomic(p, []byte("b"), 0o640); !changed {
		t.Fatal("new content not reported")
	}
	b, _ := os.ReadFile(p)
	entries, _ := os.ReadDir(dir)
	if string(b) != "b" || len(entries) != 1 || strings.HasPrefix(entries[0].Name(), ".") {
		t.Fatalf("unexpected state: %q %v", b, entries)
	}
}
