// Package typegen writes typed definitions of a project's tables, views and
// functions for the SDKs (V4 §3.7): TypeScript, Dart and Go, from the data
// API's catalog. Each table gets a row type, and tables an insert and an
// update type, whose optional fields are the columns with a default or
// that may be null.
package typegen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/token"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"unicode"

	"github.com/israel-duff/xenibase/internal/datacat"
)

// Languages.
const (
	TS   = "ts"
	Dart = "dart"
	Go   = "go"
)

// Options for Generate.
type Options struct {
	Ref     string // the project reference, for the header
	Package string // Go's package name (default "pgdtypes")
}

// Generate renders cat in lang. Database names are data, never source:
// they reach the output only escaped as string literals or comments, and
// identifiers are made from their letters and digits alone (numbered when
// two names come out the same). A name Go's encoding/json can't use as a
// tag is refused for Go.
func Generate(cat *datacat.Catalog, lang string, o Options) (string, error) {
	switch lang {
	case TS:
		return genTS(cat, o), nil
	case Dart:
		return genDart(cat, o), nil
	case Go:
		return genGo(cat, o)
	}
	return "", fmt.Errorf("unknown language %q: ts, dart or go", lang)
}

func header(comment, ref string) string {
	return fmt.Sprintf("%s Generated by xenibase gen types for project %s. Do not edit: run it again after changing the schema.\n", comment, ref)
}

// relations groups a catalog's relations by schema, in order.
func relations(cat *datacat.Catalog) (schemas []string, bySchema map[string][]*datacat.Table) {
	bySchema = map[string][]*datacat.Table{}
	for _, t := range cat.Tables() {
		bySchema[t.Schema] = append(bySchema[t.Schema], t)
	}
	for _, s := range cat.Schemas {
		if len(bySchema[s]) > 0 || len(functionsIn(cat, s)) > 0 {
			schemas = append(schemas, s)
		}
	}
	return schemas, bySchema
}

func functionsIn(cat *datacat.Catalog, schema string) []*datacat.Function {
	var out []*datacat.Function
	var keys []string
	for k := range cat.Functions {
		if strings.HasPrefix(k, schema+".") {
			keys = append(keys, k)
		}
	}
	sort.Strings(keys)
	for _, k := range keys {
		out = append(out, cat.Functions[k]...)
	}
	return out
}

func writable(t *datacat.Table) bool {
	return t.Kind == datacat.KindTable || t.Kind == datacat.KindPart
}

// optional reports whether an insert may leave c out.
func optional(c *datacat.Column) bool { return c.Nullable || c.HasDefault }

// camel turns snake_case into CamelCase (upper) or camelCase. Only
// letters and digits are kept (ASCII ones only with ascii, for Dart and
// TypeScript); anything else starts a new word. The result starts with a
// letter, upper-case when upper: X is put in front otherwise.
func camel(s string, upper, ascii bool) string {
	var b strings.Builder
	up := upper
	for _, r := range s {
		word := unicode.IsLetter(r) || unicode.IsDigit(r)
		if ascii {
			word = r < unicode.MaxASCII && word
		}
		switch {
		case !word:
			up = b.Len() > 0 || upper
		case up:
			b.WriteRune(unicode.ToUpper(r))
			up = false
		case b.Len() == 0 && !upper:
			b.WriteRune(unicode.ToLower(r))
		default:
			b.WriteRune(r)
		}
	}
	out := b.String()
	if out == "" {
		return "X"
	}
	first := []rune(out)[0]
	if !unicode.IsLetter(first) || (upper && !unicode.IsUpper(first)) {
		out = "X" + out
	}
	return out
}

// goName also upper-cases common initialisms (ID, URL).
func goName(s string) string {
	n := camel(s, true, false)
	for _, w := range []string{"Id", "Url", "Uuid", "Api", "Json", "Http", "Ip"} {
		if strings.HasSuffix(n, w) {
			n = strings.TrimSuffix(n, w) + strings.ToUpper(w)
		}
	}
	return n
}

// namer hands out identifiers that are unique in one scope: a name already
// taken (or reserved) gets 2, 3… after it. With suffixes, every name+suffix
// must be free too (Go's Todos, TodosTable, TodosInsert, TodosUpdate).
type namer map[string]bool

func newNamer(reserved ...string) namer {
	n := namer{}
	for _, r := range reserved {
		n[r] = true
	}
	return n
}

func (n namer) name(base string, suffixes ...string) string {
	free := func(s string) bool {
		if n[s] {
			return false
		}
		for _, x := range suffixes {
			if n[s+x] {
				return false
			}
		}
		return true
	}
	out := base
	for i := 2; !free(out); i++ {
		out = base + strconv.Itoa(i)
	}
	n[out] = true
	for _, x := range suffixes {
		n[out+x] = true
	}
	return out
}

// comment is text for a line comment: as it is when every character prints,
// quoted otherwise, so a newline (or a JavaScript line separator) can't end
// the comment.
func comment(s string) string {
	for _, r := range s {
		if !unicode.IsPrint(r) {
			return strconv.Quote(s)
		}
	}
	return s
}

// jsString is s as a TypeScript string literal (JSON's escaping, which
// also covers U+2028 and U+2029).
func jsString(s string) string {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	_ = enc.Encode(s)
	return strings.TrimSuffix(b.String(), "\n")
}

// dartString is s as a Dart string literal: single-quoted, with $ escaped
// so nothing is interpolated.
func dartString(s string) string {
	var b strings.Builder
	b.WriteByte('\'')
	for _, r := range s {
		switch {
		case r == '\\' || r == '\'' || r == '$':
			b.WriteByte('\\')
			b.WriteRune(r)
		case r == '\n':
			b.WriteString(`\n`)
		case r == '\r':
			b.WriteString(`\r`)
		case r == '\t':
			b.WriteString(`\t`)
		case !unicode.IsPrint(r):
			fmt.Fprintf(&b, `\u{%x}`, r)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('\'')
	return b.String()
}

// goTag is c's json tag name, or an error when encoding/json would ignore
// it (it allows letters, digits, spaces and !#$%&()*+-./:;<=>?@[]^_{|}~),
// which also keeps quotes, backquotes and backslashes out of the tag.
func goTag(t *datacat.Table, c string) (string, error) {
	ok := c != ""
	for _, r := range c {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) && !strings.ContainsRune("!#$%&()*+-./:;<=>?@[]^_{|}~ ", r) {
			ok = false
		}
	}
	if !ok {
		return "", fmt.Errorf("column %s of %s.%s can't be a Go JSON field: encoding/json allows letters, digits, spaces and !#$%%&()*+-./:;<=>?@[]^_{|}~ in a name; rename it, or generate TypeScript or Dart",
			strconv.Quote(c), strconv.Quote(t.Schema), strconv.Quote(t.Name))
	}
	return c, nil
}

var goPackageRe = regexp.MustCompile(`^[a-z_][a-z0-9_]*$`)

// ---- TypeScript -------------------------------------------------------------

func tsType(c *datacat.Column) string {
	var t string
	elem := strings.TrimPrefix(c.TypName, "_")
	switch {
	case len(c.Enum) > 0:
		var labels []string
		for _, l := range c.Enum {
			labels = append(labels, jsString(l))
		}
		t = strings.Join(labels, " | ")
	case c.Category == 'A':
		t = tsScalar(elem) + "[]"
	default:
		t = tsScalar(c.TypName)
	}
	if c.Nullable {
		t += " | null"
	}
	return t
}

func tsScalar(typname string) string {
	switch typname {
	case "int2", "int4", "int8", "float4", "float8", "numeric", "oid", "money":
		return "number"
	case "bool":
		return "boolean"
	case "json", "jsonb":
		return "Json"
	}
	return "string"
}

// tsKey is a property name: bare when it is a plain identifier, a string
// literal otherwise.
func tsKey(name string) string {
	for i, r := range name {
		if r >= unicode.MaxASCII || (!unicode.IsLetter(r) && r != '_' && r != '$' && (i == 0 || !unicode.IsDigit(r))) {
			return jsString(name)
		}
	}
	if name == "" {
		return jsString(name)
	}
	return name
}

func genTS(cat *datacat.Catalog, o Options) string {
	var b strings.Builder
	b.WriteString(header("//", o.Ref))
	b.WriteString("\nexport type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\n\n")
	b.WriteString("export interface Database {\n")
	schemas, by := relations(cat)
	for _, s := range schemas {
		fmt.Fprintf(&b, "  %s: {\n    Tables: {\n", tsKey(s))
		for _, t := range by[s] {
			if !writable(t) {
				continue
			}
			fmt.Fprintf(&b, "      %s: {\n        Row: {\n", tsKey(t.Name))
			for _, c := range t.Columns {
				fmt.Fprintf(&b, "          %s: %s;\n", tsKey(c.Name), tsType(c))
			}
			b.WriteString("        };\n        Insert: {\n")
			for _, c := range t.Columns {
				if c.Generated {
					continue
				}
				q := ""
				if optional(c) {
					q = "?"
				}
				fmt.Fprintf(&b, "          %s%s: %s;\n", tsKey(c.Name), q, tsType(c))
			}
			b.WriteString("        };\n        Update: {\n")
			for _, c := range t.Columns {
				if c.Generated {
					continue
				}
				fmt.Fprintf(&b, "          %s?: %s;\n", tsKey(c.Name), tsType(c))
			}
			b.WriteString("        };\n      };\n")
		}
		b.WriteString("    };\n    Views: {\n")
		for _, t := range by[s] {
			if writable(t) {
				continue
			}
			fmt.Fprintf(&b, "      %s: {\n        Row: {\n", tsKey(t.Name))
			for _, c := range t.Columns {
				fmt.Fprintf(&b, "          %s: %s;\n", tsKey(c.Name), tsType(c))
			}
			b.WriteString("        };\n      };\n")
		}
		b.WriteString("    };\n    Functions: {\n")
		seen := map[string]bool{}
		for _, f := range functionsIn(cat, s) {
			if seen[f.Name] {
				continue // overloads: the first
			}
			seen[f.Name] = true
			fmt.Fprintf(&b, "      %s: {\n        Args: {", tsKey(f.Name))
			for _, a := range f.Args {
				if a.Name == "" {
					continue
				}
				q := ""
				if a.HasDefault {
					q = "?"
				}
				c := &datacat.Column{TypName: a.TypName, Category: a.Category}
				fmt.Fprintf(&b, " %s%s: %s;", tsKey(a.Name), q, tsType(c))
			}
			b.WriteString(" };\n        Returns: ")
			switch {
			case f.Columns != nil:
				b.WriteString("{")
				for _, c := range f.Columns {
					fmt.Fprintf(&b, " %s: %s;", tsKey(c.Name), tsType(c))
				}
				b.WriteString(" }")
				if f.RetSet {
					b.WriteString("[]")
				}
			default:
				b.WriteString(tsType(&datacat.Column{TypName: f.RetTypName, Category: f.RetCategory, Nullable: true}))
				if f.RetSet {
					b.WriteString("[]")
				}
			}
			b.WriteString(";\n      };\n")
		}
		b.WriteString("    };\n  };\n")
	}
	b.WriteString("}\n\n")
	// Shorthands: Tables<"todos">, and one alias per table.
	if len(schemas) > 0 {
		def := jsString(schemas[0])
		fmt.Fprintf(&b, "export type Tables<T extends keyof Database[%s][\"Tables\"]> = Database[%s][\"Tables\"][T][\"Row\"];\n", def, def)
		fmt.Fprintf(&b, "export type TablesInsert<T extends keyof Database[%s][\"Tables\"]> = Database[%s][\"Tables\"][T][\"Insert\"];\n", def, def)
		fmt.Fprintf(&b, "export type TablesUpdate<T extends keyof Database[%s][\"Tables\"]> = Database[%s][\"Tables\"][T][\"Update\"];\n", def, def)
		names := newNamer("Json", "Database", "Tables", "TablesInsert", "TablesUpdate")
		for _, t := range by[schemas[0]] {
			kind := "Tables"
			if !writable(t) {
				kind = "Views"
			}
			fmt.Fprintf(&b, "export type %s = Database[%s][%q][%s][\"Row\"];\n", names.name(camel(t.Name, true, true)), def, kind, jsString(t.Name))
		}
	}
	return b.String()
}

// ---- Dart -------------------------------------------------------------------

func dartScalar(typname string) string {
	switch typname {
	case "int2", "int4", "int8", "oid":
		return "int"
	case "float4", "float8", "numeric", "money":
		return "num"
	case "bool":
		return "bool"
	case "json", "jsonb":
		return "dynamic"
	case "timestamptz", "timestamp":
		return "DateTime"
	}
	return "String"
}

func dartType(c *datacat.Column) string {
	t := dartScalar(c.TypName)
	if c.Category == 'A' {
		t = "List<" + dartScalar(strings.TrimPrefix(c.TypName, "_")) + ">"
	}
	if c.Nullable && t != "dynamic" {
		t += "?"
	}
	return t
}

func dartFrom(c *datacat.Column, expr string) string {
	base := dartScalar(c.TypName)
	nullable := c.Nullable
	switch {
	case c.Category == 'A':
		elem := dartScalar(strings.TrimPrefix(c.TypName, "_"))
		conv := "(" + expr + " as List).map((e) => e as " + elem + ").toList()"
		if elem == "num" {
			conv = "(" + expr + " as List).map((e) => e as num).toList()"
		}
		if nullable {
			return expr + " == null ? null : " + conv
		}
		return conv
	case base == "DateTime":
		if nullable {
			return expr + " == null ? null : DateTime.parse(" + expr + " as String)"
		}
		return "DateTime.parse(" + expr + " as String)"
	case base == "dynamic":
		return expr
	}
	if nullable {
		return expr + " as " + base + "?"
	}
	return expr + " as " + base
}

func dartTo(c *datacat.Column, field string) string {
	if dartScalar(c.TypName) == "DateTime" && c.Category != 'A' {
		if c.Nullable {
			return field + "?.toIso8601String()"
		}
		return field + ".toIso8601String()"
	}
	return field
}

// Dart's reserved words and built-in identifiers, and the members every
// generated class has: a field may not take these names.
var dartReserved = strings.Fields(`abstract as assert async await base break case catch class const continue covariant default
	deferred do dynamic else enum export extends extension external factory false final finally for Function get hide if
	implements import in interface is late library mixin new null of on operator part required rethrow return sealed set
	show static super switch sync this throw true try type typedef var void when while with yield
	table fromJson toJson hashCode runtimeType toString noSuchMethod`)

// The types the generated Dart uses: a class may not take these names.
var dartTypes = []string{"List", "Map", "String", "DateTime", "int", "num", "bool", "dynamic", "Object", "Null", "double",
	"Function", "Type", "Never", "Iterable", "Set", "Symbol", "Record", "Enum", "Future", "Stream", "Duration", "Uri", "BigInt"}

func genDart(cat *datacat.Catalog, o Options) string {
	var b strings.Builder
	b.WriteString(header("//", o.Ref))
	b.WriteString("// ignore_for_file: type=lint\n\n")
	schemas, by := relations(cat)
	classes := newNamer(dartTypes...)
	for _, s := range schemas {
		for _, t := range by[s] {
			base := camel(t.Name, true, true)
			if s != cat.Schemas[0] {
				base = camel(s, true, true) + base
			}
			name := classes.name(base)
			fields := newNamer()
			field := map[*datacat.Column]string{}
			for _, c := range t.Columns {
				f := camel(c.Name, false, true)
				for _, r := range dartReserved {
					if f == r {
						f += "_"
					}
				}
				field[c] = fields.name(f)
			}
			fmt.Fprintf(&b, "/// A row of %s.\nclass %s {\n", comment(t.Schema+"."+t.Name), name)
			for _, c := range t.Columns {
				fmt.Fprintf(&b, "  final %s %s;\n", dartType(c), field[c])
			}
			fmt.Fprintf(&b, "\n  const %s({", name)
			for i, c := range t.Columns {
				if i > 0 {
					b.WriteString(", ")
				}
				if c.Nullable {
					fmt.Fprintf(&b, "this.%s", field[c])
				} else {
					fmt.Fprintf(&b, "required this.%s", field[c])
				}
			}
			b.WriteString("});\n\n")
			fmt.Fprintf(&b, "  static const table = %s;\n\n", dartString(t.Name))
			fmt.Fprintf(&b, "  factory %s.fromJson(Map<String, dynamic> json) => %s(\n", name, name)
			for _, c := range t.Columns {
				fmt.Fprintf(&b, "        %s: %s,\n", field[c], dartFrom(c, "json["+dartString(c.Name)+"]"))
			}
			b.WriteString("      );\n\n  Map<String, dynamic> toJson() => {\n")
			for _, c := range t.Columns {
				if c.Generated {
					continue
				}
				fmt.Fprintf(&b, "        %s: %s,\n", dartString(c.Name), dartTo(c, field[c]))
			}
			b.WriteString("      };\n}\n\n")
		}
	}
	return b.String()
}

// ---- Go ---------------------------------------------------------------------

func goScalar(typname string) string {
	switch typname {
	case "int2":
		return "int16"
	case "int4":
		return "int32"
	case "int8", "oid":
		return "int64"
	case "float4":
		return "float32"
	case "float8":
		return "float64"
	case "numeric", "money":
		return "json.Number"
	case "bool":
		return "bool"
	case "json", "jsonb":
		return "json.RawMessage"
	case "timestamptz", "timestamp":
		return "time.Time"
	}
	return "string"
}

func goType(c *datacat.Column, ptr bool) string {
	t := goScalar(c.TypName)
	if c.Category == 'A' {
		return "[]" + goScalar(strings.TrimPrefix(c.TypName, "_"))
	}
	if t == "json.RawMessage" {
		return t
	}
	if ptr {
		return "*" + t
	}
	return t
}

func genGo(cat *datacat.Catalog, o Options) (string, error) {
	pkg := o.Package
	if pkg == "" {
		pkg = "pgdtypes"
	}
	if !goPackageRe.MatchString(pkg) || token.IsKeyword(pkg) {
		return "", fmt.Errorf("%q is not a Go package name", pkg)
	}
	var body strings.Builder
	usesTime, usesJSON := false, false
	note := func(t string) {
		if strings.Contains(t, "time.") {
			usesTime = true
		}
		if strings.Contains(t, "json.") {
			usesJSON = true
		}
	}
	schemas, by := relations(cat)
	types := newNamer()
	for _, s := range schemas {
		for _, t := range by[s] {
			base := goName(t.Name)
			if s != cat.Schemas[0] {
				base = goName(s) + base
			}
			name := types.name(base, "Table", "Insert", "Update")
			fields := newNamer()
			field, tag := map[*datacat.Column]string{}, map[*datacat.Column]string{}
			for _, c := range t.Columns {
				field[c] = fields.name(goName(c.Name))
				var err error
				if tag[c], err = goTag(t, c.Name); err != nil {
					return "", err
				}
			}
			ref := comment(t.Schema + "." + t.Name)
			fmt.Fprintf(&body, "// %s is a row of %s.\ntype %s struct {\n", name, ref, name)
			for _, c := range t.Columns {
				gt := goType(c, c.Nullable)
				note(gt)
				fmt.Fprintf(&body, "\t%s %s `json:%s`\n", field[c], gt, strconv.Quote(tag[c]))
			}
			body.WriteString("}\n\n")
			fmt.Fprintf(&body, "// %sTable is the name to use in data API paths.\nconst %sTable = %s\n\n", name, name, strconv.Quote(tableRef(cat, t)))
			if !writable(t) {
				continue
			}
			fmt.Fprintf(&body, "// %sInsert is a new row: nil fields take the column's default or null.\ntype %sInsert struct {\n", name, name)
			for _, c := range t.Columns {
				if c.Generated {
					continue
				}
				gt := goType(c, optional(c))
				note(gt)
				tg := tag[c]
				if optional(c) {
					tg += ",omitempty"
				}
				fmt.Fprintf(&body, "\t%s %s `json:%s`\n", field[c], gt, strconv.Quote(tg))
			}
			body.WriteString("}\n\n")
			fmt.Fprintf(&body, "// %sUpdate changes the non-nil fields.\ntype %sUpdate struct {\n", name, name)
			for _, c := range t.Columns {
				if c.Generated {
					continue
				}
				gt := goType(c, true)
				note(gt)
				fmt.Fprintf(&body, "\t%s %s `json:%s`\n", field[c], gt, strconv.Quote(tag[c]+",omitempty"))
			}
			body.WriteString("}\n\n")
		}
	}
	var b strings.Builder
	b.WriteString(header("//", o.Ref))
	fmt.Fprintf(&b, "\n// Package %s holds the project's table types.\npackage %s\n\n", pkg, pkg)
	switch {
	case usesTime && usesJSON:
		b.WriteString("import (\n\t\"encoding/json\"\n\t\"time\"\n)\n\n")
	case usesTime:
		b.WriteString("import \"time\"\n\n")
	case usesJSON:
		b.WriteString("import \"encoding/json\"\n\n")
	}
	b.WriteString(body.String())
	return b.String(), nil
}

func tableRef(cat *datacat.Catalog, t *datacat.Table) string {
	if t.Schema == cat.Schemas[0] {
		return t.Name
	}
	return t.Schema + "." + t.Name
}
